"""Dump OpenAPI JSON and a TypeScript schema used by the frontend (decision D22)."""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "backend"))

from app.config import BackendSettings  # noqa: E402
from app.main import create_app  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
OPENAPI = ROOT / "frontend" / "src" / "api" / "openapi.json"
SCHEMA = ROOT / "frontend" / "src" / "api" / "schema.ts"


def build() -> dict:
    settings = BackendSettings(
        _env_file=None,
        app_env="test",
        app_secret_key="test-secret-key-0123456789-abcdefghijklmnopqrstuvwxyz",
        database_url="sqlite://",
        frontend_dist=ROOT / "frontend" / "dist",
        data_dir=ROOT / "data" / "tmp_openapi",
        purge_interval_seconds=0,
    )
    app = create_app(settings)
    return app.openapi()


def ts_module(spec: dict) -> str:
    """A small generated module: path+method keys. Full types come from openapi.json."""
    paths = spec.get("paths", {})
    lines = [
        "/* Generated by scripts/export_openapi.py. Do not edit by hand. */",
        "export const API_PATHS = [",
    ]
    for path, methods in sorted(paths.items()):
        for method in sorted(methods):
            if method.startswith("x-") or method == "parameters":
                continue
            lines.append(f"  '{method.upper()} {path}',")
    lines += ["] as const", "export type ApiPath = (typeof API_PATHS)[number]", ""]
    return "\n".join(lines)


def main() -> None:
    spec = build()
    OPENAPI.parent.mkdir(parents=True, exist_ok=True)
    OPENAPI.write_text(json.dumps(spec, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    SCHEMA.write_text(ts_module(spec), encoding="utf-8")
    print(f"wrote {OPENAPI} and {SCHEMA}")


if __name__ == "__main__":
    main()
