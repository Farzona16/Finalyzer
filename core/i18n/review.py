"""Builds ``docs/uz_review.md``: every Uzbek string the owner has not reviewed yet (spec 5.4).

Sources: frames and glossary entries flagged ``reviewed: false``, the backend catalog
``backend/app/locales/uz.json`` and the frontend catalog ``frontend/src/i18n/uz.json`` (both
have no review flag, so every entry is listed until the owner confirms the file).
"""

from __future__ import annotations

import json
from pathlib import Path

from core.i18n.frames import TEXT_FIELDS

ROOT = Path(__file__).resolve().parents[2]
FRAME_FILE = ROOT / "core" / "i18n" / "frames_uz.json"
GLOSSARY_FILE = ROOT / "core" / "i18n" / "glossary_uz.json"
CATALOGS = (
    ("Backend messages", ROOT / "backend" / "app" / "locales" / "uz.json"),
    ("Frontend messages", ROOT / "frontend" / "src" / "i18n" / "uz.json"),
)
OUTPUT = ROOT / "docs" / "uz_review.md"


def _escape(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _load(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def unreviewed_frames(path: Path = FRAME_FILE) -> dict[str, dict]:
    """Frames with ``reviewed: false``."""
    return {k: v for k, v in _load(path)["frames"].items() if not v.get("reviewed")}


def unreviewed_glossary(path: Path = GLOSSARY_FILE) -> dict[str, dict]:
    """Glossary entries with ``reviewed: false``."""
    return {k: v for k, v in _load(path)["entries"].items() if not v.get("reviewed")}


def build_markdown(
    frame_file: Path = FRAME_FILE,
    glossary_file: Path = GLOSSARY_FILE,
    catalogs: tuple[tuple[str, Path], ...] = CATALOGS,
) -> str:
    """The whole review document as text."""
    frames = unreviewed_frames(frame_file)
    entries = unreviewed_glossary(glossary_file)
    lines = [
        "# Uzbek text waiting for review",
        "",
        "Generated by `python scripts/gen_uz_review.py`. Do not edit by hand: set "
        "`\"reviewed\": true` in the JSON file after a native speaker has checked a text, "
        "then run the script again.",
        "",
        "What to look for: natural wording, the letters `o\u02bb` and `g\u02bb` (U+02BB), the "
        "apostrophe `'` only for the tutuq belgisi, short sentences, no suffix glued to a value "
        "in `\u00ab{...}\u00bb`.",
        "",
        f"* Frames: {len(frames)}",
        f"* Glossary entries: {len(entries)}",
    ]
    catalog_data = []
    for title, path in catalogs:
        if path.exists():
            data = _load(path)
            catalog_data.append((title, path, data))
            lines.append(f"* {title}: {len(data)}")
    lines += ["", "## Message frames", "", "| Key | Headline | Meaning | Next step | Details |",
              "|---|---|---|---|---|"]
    for key, frame in frames.items():
        cells = [_escape(str(frame.get(field, ""))) for field in TEXT_FIELDS]
        lines.append(f"| `{key}` | " + " | ".join(cells) + " |")
    lines += ["", "## Glossary", "", "| Key | Term | Plain explanation |", "|---|---|---|"]
    for key, entry in entries.items():
        lines.append(f"| `{key}` | {_escape(entry['term'])} | {_escape(entry['plain'])} |")
    for title, path, data in catalog_data:
        lines += ["", f"## {title}", "", f"File: `{path.relative_to(ROOT).as_posix()}`", "",
                  "| Key | Text |", "|---|---|"]
        for key, text in data.items():
            lines.append(f"| `{key}` | {_escape(str(text))} |")
    return "\n".join(lines) + "\n"


def write(path: Path = OUTPUT) -> Path:
    """Write the document and return its path."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(build_markdown(), encoding="utf-8")
    return path
