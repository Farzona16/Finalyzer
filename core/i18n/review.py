"""Builds ``docs/uz_review.md``: every Uzbek string the owner has not reviewed yet (spec 5.4).

Sources: frames and glossary entries flagged ``reviewed: false``, the backend catalog
``backend/app/locales/uz.json`` and the frontend catalog ``frontend/src/i18n/uz.json`` (both
have no review flag, so every entry is listed until the owner confirms the file).
"""

from __future__ import annotations

import json
from pathlib import Path

from core.i18n.frames import TEXT_FIELDS

ROOT = Path(__file__).resolve().parents[2]
FRAME_FILE = ROOT / "core" / "i18n" / "frames_uz.json"
GLOSSARY_FILE = ROOT / "core" / "i18n" / "glossary_uz.json"
CATALOGS = (
    ("Backend messages", ROOT / "backend" / "app" / "locales" / "uz.json"),
    ("Frontend messages", ROOT / "frontend" / "src" / "i18n" / "uz.json"),
)
OUTPUT = ROOT / "docs" / "uz_review.md"


def _escape(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _load(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def unreviewed_frames(path: Path = FRAME_FILE) -> dict[str, dict]:
    """Frames with ``reviewed: false``."""
    return {k: v for k, v in _load(path)["frames"].items() if not v.get("reviewed")}


def unreviewed_glossary(path: Path = GLOSSARY_FILE) -> dict[str, dict]:
    """Glossary entries with ``reviewed: false``."""
    return {k: v for k, v in _load(path)["entries"].items() if not v.get("reviewed")}


def pack_strings() -> list[tuple[str, str, str]]:
    """``(source, key, Uzbek text)`` of every pack, autopilot label and dashboard title.

    These texts have no ``reviewed`` flag yet, so all of them are listed until the owner has
    confirmed the files ``core/metrics/packs/*.yaml``, ``core/autopilot/labels.json`` and
    ``core/templates/dashboards/*.json``.
    """
    from core.autopilot.heuristics import label_templates
    from core.metrics.registry import list_pack_names, load_pack
    from core.templates.resolver import list_templates, load_template

    rows: list[tuple[str, str, str]] = []
    for name in list_pack_names():
        pack = load_pack(name)
        rows.append((f"pack {name}", "labels", pack.labels.get("uz", "")))
        rows += [(f"pack {name}", "question", q) for q in pack.suggested_questions.get("uz", [])]
        for metric in pack.metrics:
            for field, value in metric.i18n.get("uz", {}).items():
                text = ", ".join(value) if isinstance(value, list) else str(value)
                rows.append((f"pack {name}", f"{metric.id}.{field}", text))
    rows += [("label template", key, t["uz"]) for key, t in label_templates().items()]
    from core.insights.nextsteps_v3 import texts as next_steps_texts

    rows += [("next steps", key, text) for key, text in next_steps_texts("uz").items()]
    answer_frames = Path(__file__).resolve().parents[1] / "nlu" / "answer_frames.json"
    if answer_frames.is_file():
        data = json.loads(answer_frames.read_text(encoding="utf-8")).get("uz", {})
        rows += [("ask frames", key, text) for key, text in data.items()]
    from core.nlu.followups import FOLLOW

    rows += [("ask followups", key, text) for key, text in FOLLOW["uz"].items()]
    for name in list_templates():
        rows += [
            (f"dashboard {name}", tile["id"], tile["title"]["uz"])
            for tile in load_template(name)["tiles"]
        ]
    return rows


def build_markdown(
    frame_file: Path = FRAME_FILE,
    glossary_file: Path = GLOSSARY_FILE,
    catalogs: tuple[tuple[str, Path], ...] = CATALOGS,
    include_packs: bool = True,
) -> str:
    """The whole review document as text."""
    frames = unreviewed_frames(frame_file)
    entries = unreviewed_glossary(glossary_file)
    lines = [
        "# Uzbek text waiting for review",
        "",
        "Generated by `python scripts/gen_uz_review.py`. Do not edit by hand: set "
        '`"reviewed": true` in the JSON file after a native speaker has checked a text, '
        "then run the script again.",
        "",
        "What to look for: natural wording, the letters `o\u02bb` and `g\u02bb` (U+02BB), the "
        "apostrophe `'` only for the tutuq belgisi, short sentences, no suffix glued to a value "
        "in `\u00ab{...}\u00bb`.",
        "",
        f"* Frames: {len(frames)}",
        f"* Glossary entries: {len(entries)}",
    ]
    catalog_data = []
    for title, path in catalogs:
        if path.exists():
            data = _load(path)
            catalog_data.append((title, path, data))
            lines.append(f"* {title}: {len(data)}")
    lines += [
        "",
        "## Message frames",
        "",
        "| Key | Headline | Meaning | Next step | Details |",
        "|---|---|---|---|---|",
    ]
    for key, frame in frames.items():
        cells = [_escape(str(frame.get(field, ""))) for field in TEXT_FIELDS]
        lines.append(f"| `{key}` | " + " | ".join(cells) + " |")
    lines += ["", "## Glossary", "", "| Key | Term | Plain explanation |", "|---|---|---|"]
    for key, entry in entries.items():
        lines.append(f"| `{key}` | {_escape(entry['term'])} | {_escape(entry['plain'])} |")
    for title, path, data in catalog_data:
        lines += [
            "",
            f"## {title}",
            "",
            f"File: `{path.relative_to(ROOT).as_posix()}`",
            "",
            "| Key | Text |",
            "|---|---|",
        ]
        for key, text in data.items():
            lines.append(f"| `{key}` | {_escape(str(text))} |")
    if include_packs:
        rows = pack_strings()
        lines += [
            "",
            "## KPI packs, labels and dashboards",
            "",
            f"Strings: {len(rows)}",
            "",
            "| Source | Key | Text |",
            "|---|---|---|",
        ]
        lines += [f"| {src} | `{key}` | {_escape(text)} |" for src, key, text in rows]
    return "\n".join(lines) + "\n"


def write(path: Path = OUTPUT) -> Path:
    """Write the document and return its path."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(build_markdown(), encoding="utf-8")
    return path
